# -*- coding: utf-8 -*-
"""
Spiking FLA – Dual-Path Spike-Controlled Convolutional Block (SPiC-Conv)
========================================================================
Identifier: spiking_fla_spicconv

This block explores an *orthogonal* architectural direction compared to the
extensive DeltaNet-family experiments that fuse many memory paths with learned
soft- or sigmoid-gates.  Instead of fusing *multiple* heavy branches, **a single
lightweight continuous path is *modulated* by a parallel spiking control path**.

Core ideas
----------
1. **Spike-to-State Parallelism** – The input is converted into spikes which are
   then passed through two independent `SpikingLinear` layers: one produces the
   *content* features, the second generates *binary* control signals that gate a
   depth-wise causal convolution path.  This separates *what* (content) from
   *when* (spike timing), reminiscent of dorsal/ventral processing streams in
   the visual cortex.
2. **Causal Depth-wise Convolution Memory** – A depth-wise 1-D causal
   convolution (kernel = 3 by default) provides short-range context with strict
   O(N) complexity and minimal parameter cost.
3. **Spike-Controlled Gating** – The gate logits generated by the spiking
   control path are squashed by a sigmoid and multiplied with the convolutional
   features, yielding event-driven, content-dependent modulation – a departure
   from probability-simplex or additive fusion designs.
4. **Fully-Spiking Feed-Forward Network** – The feed-forward sub-block is built
   *exclusively* from `SpikingLinear` layers, ensuring every linear
   transformation consumes **binary spikes**.
5. **Unified Spike Aggregation** – All spikes created inside the block are
   flattened and concatenated into a single 1-D tensor `final_spikes` which is
   returned alongside the usual `(output, reg_loss)` tuple.

All requirements are met:
• every linear transformation is realised through `SpikingLinear`;
• tensor reshaping uses only `einops.rearrange()`;
• operations are strictly causal and O(N);
• the public API of `SpikingFLABlock.forward` is unchanged.
"""
from __future__ import annotations

from typing import Tuple, Optional, List, Dict

import torch
import torch.nn as nn
import torch.nn.functional as F
from einops import rearrange

try:
    from src.models.spike.neuron import registry as neuron_registry
    from src.models.spike.surrogate import piecewise_quadratic_surrogate
except ImportError:  # pragma: no cover
    print("Warning: Spiking neuron modules (src.models.spike) not found.")
    neuron_registry = None  # type: ignore
    piecewise_quadratic_surrogate = None  # type: ignore

# -----------------------------------------------------------------------------
# SpikingLinear (MUST remain unmodified)
# -----------------------------------------------------------------------------
class SpikingLinear(nn.Module):
    """A Linear Module preceded by a spiking neuron layer."""

    def __init__(self, linear_layer: nn.Linear, neuron_type: str, surrogate_function):
        super().__init__()
        self.neuron = neuron_registry[neuron_type](surrogate_function=surrogate_function)
        self.linear = linear_layer

    def forward(self, x: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        # Convert to (B, D, L) for neuron which expects channel first
        spikes_transposed = self.neuron(x.transpose(-1, -2))  # (B, D, L)
        spikes = spikes_transposed.transpose(-1, -2)          # back to (B, L, D)
        out = self.linear(spikes)
        return out, spikes

# -----------------------------------------------------------------------------
# Depth-wise causal 1-D convolution (identity initialised)
# -----------------------------------------------------------------------------
class CausalDepthwiseConv1d(nn.Module):
    """Depth-wise causal convolution with identity start (Dirac init)."""

    def __init__(self, channels: int, kernel_size: int = 3):
        super().__init__()
        self.kernel_size = int(kernel_size)
        self.conv = nn.Conv1d(
            in_channels=channels,
            out_channels=channels,
            kernel_size=self.kernel_size,
            groups=channels,
            bias=False,
        )
        # Dirac initialisation (identity mapping at start)
        with torch.no_grad():
            self.conv.weight.zero_()
            self.conv.weight[:, :, -1] = 1.0

    def forward(self, x: torch.Tensor) -> torch.Tensor:  # x: (B,L,D)
        x_t = rearrange(x, "b l d -> b d l")
        x_pad = F.pad(x_t, (self.kernel_size - 1, 0))  # causal left pad
        y = self.conv(x_pad)
        return rearrange(y, "b d l -> b l d")

# -----------------------------------------------------------------------------
# Fully-spiking Feed-Forward Network
# -----------------------------------------------------------------------------
class SpikingFeedForward(nn.Module):
    """Two-layer feed-forward network built from SpikingLinear."""

    def __init__(
        self,
        d_model: int,
        d_ffn: int,
        dropout: float = 0.1,
        *,
        neuron_type: str = "sdn",
    ) -> None:
        super().__init__()
        if neuron_registry is None:
            raise ImportError("Spiking modules not available – cannot build SpikingFeedForward.")

        self.lin1 = SpikingLinear(nn.Linear(d_model, d_ffn, bias=False), neuron_type, piecewise_quadratic_surrogate())
        self.lin2 = SpikingLinear(nn.Linear(d_ffn, d_model, bias=False), neuron_type, piecewise_quadratic_surrogate())
        self.dropout = nn.Dropout(dropout)

    def forward(self, x: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        h, spikes = [], []  # type: List[torch.Tensor], List[torch.Tensor]

        x1, s1 = self.lin1(x)
        spikes.append(rearrange(s1, "b l d -> (b l d)"))
        x1 = F.gelu(x1)
        x1 = self.dropout(x1)

        x2, s2 = self.lin2(x1)
        spikes.append(rearrange(s2, "b l d -> (b l d)"))
        x2 = self.dropout(x2)

        final_spikes = torch.cat(spikes, dim=0)
        return x2, final_spikes

# -----------------------------------------------------------------------------
# Main SpikingFLABlock (SPiC-Conv)
# -----------------------------------------------------------------------------
class SpikingFLABlock(nn.Module):  # noqa: D401 – name is fixed by requirements
    """Dual-path spike-controlled convolutional processing block."""

    def __init__(
        self,
        d_model: int,
        num_heads: int,                    # kept for interface compat (unused)
        use_spiking_mlp: bool = True,      # compat flag (always spiking internally)
        d_ffn_mult: int = 4,
        dropout: float = 0.1,
        prenorm: bool = True,
        neuron_type: str = "sdn",
        conv_kernel_size: int = 3,
        **kwargs: Dict,                    # absorb & ignore extra params
    ) -> None:
        super().__init__()
        if neuron_registry is None:
            raise ImportError("Spiking neuron modules are not available.")

        self.prenorm = prenorm
        self.norm1 = nn.LayerNorm(d_model)
        self.norm2 = nn.LayerNorm(d_model)

        # === Dual spiking projections (content & gate) ===
        self.content_proj = SpikingLinear(nn.Linear(d_model, d_model, bias=False), neuron_type, piecewise_quadratic_surrogate())
        self.gate_proj    = SpikingLinear(nn.Linear(d_model, d_model, bias=False), neuron_type, piecewise_quadratic_surrogate())

        # === Continuous causal conv path ===
        self.conv_path = CausalDepthwiseConv1d(d_model, kernel_size=conv_kernel_size)

        self.dropout = nn.Dropout(dropout)

        # === Feed-forward ===
        d_ffn = d_model * d_ffn_mult
        self.ffn = SpikingFeedForward(d_model, d_ffn, dropout=dropout, neuron_type=neuron_type)
        self.dropout_ffn = nn.Dropout(dropout)

    # ---------------------------------------------------------------------
    # forward
    # ---------------------------------------------------------------------
    def forward(self, x: torch.Tensor, **kwargs):  # noqa: D401 signature fixed
        # -----------------------------------------------------------------
        # Stage 1: (optional) pre-norm
        # -----------------------------------------------------------------
        residual = x
        if self.prenorm:
            x = self.norm1(x)

        # -----------------------------------------------------------------
        # Dual spiking projections
        # -----------------------------------------------------------------
        content_out, spikes_content = self.content_proj(x)   # (B,L,D)
        gate_logits, spikes_gate   = self.gate_proj(x)       # (B,L,D)
        gate = torch.sigmoid(gate_logits)

        # -----------------------------------------------------------------
        # Convolutional path (causal)
        # -----------------------------------------------------------------
        conv_out = self.conv_path(x)  # uses same (B,L,D) shape

        # Spike-controlled fusion
        fused = gate * conv_out + (1.0 - gate) * content_out
        fused = self.dropout(fused)
        x = residual + fused  # residual connection

        # -----------------------------------------------------------------
        # Stage 2: Feed-forward
        # -----------------------------------------------------------------
        residual_ffn = x
        if self.prenorm:
            x = self.norm2(x)

        ffn_out, spikes_ffn = self.ffn(x)
        x = residual_ffn + self.dropout_ffn(ffn_out)

        # -----------------------------------------------------------------
        # Aggregate spikes – flat 1-D tensor
        # -----------------------------------------------------------------
        spikes_flat_content = rearrange(spikes_content, "b l d -> (b l d)")
        spikes_flat_gate    = rearrange(spikes_gate,    "b l d -> (b l d)")
        final_spikes = torch.cat([spikes_flat_content, spikes_flat_gate, spikes_ffn], dim=0)

        # reg_loss placeholder for API compatibility
        reg_loss: Optional[torch.Tensor] = None

        return x, reg_loss, final_spikes
