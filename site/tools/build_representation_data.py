#!/usr/bin/env python3
"""Generate site/js/representation-data.js: the 21-D behavioural fingerprint of every trained
architecture (as logged in the evaluated archive) plus the fixed similarity scaling bounds.

    python3 site/tools/build_representation_data.py

Kept separate from build_data.py (which wipes site/data/) so the representation section works
without another data file. Values are copied verbatim (rounded to 6 significant digits); the
join key is (group, sample_num) between site/data/architectures.json and the curated delivery.
"""
import json
import os
from pathlib import Path

SITE = Path(__file__).resolve().parents[1]
WORK = Path(os.environ.get("OAE_WORK", Path(__file__).resolve().parents[4]))
PKG = Path(os.environ.get("OAE_PKG", WORK / "Source_Code/OpenArchEvo"))

schema = json.loads((PKG / "configs/fingerprint_schema.json").read_text())
recs = [json.loads(l) for l in (PKG / "architectures/architectures.jsonl").read_text().splitlines() if l.strip()]
by = {(r["group"], r["sample_num"]): r["fingerprint"] for r in recs}
archs = json.loads((SITE / "data/architectures.json").read_text())

keys = schema["feature_keys"]
bounds = {b["feature"]: [b["p05"], b["p95"]] for b in schema["fixed_similarity_scaling_bounds"]}
assert [b["feature"] for b in schema["fixed_similarity_scaling_bounds"]] == keys

fp, missing = {}, []
for a in archs:
    f = by.get((a["group"], a["sample"]))
    if not f or len(f.get("values") or []) != len(keys):
        missing.append(a["key"]); continue
    fp[a["key"]] = [float(f"{v:.6g}") for v in f["values"]]

out = {
    "schema": schema["schema_version"],
    "keys": keys,
    "bounds": [bounds[k] for k in keys],
    "scale_c": 0.9,
    "fp": fp,
}
js = ("// GENERATED by site/tools/build_representation_data.py, do not edit by hand.\n"
      "// Source: Source_Code/OpenArchEvo/architectures/architectures.jsonl (fingerprint.values, provenance 'logged')\n"
      "// and configs/fingerprint_schema.json (fixed_similarity_scaling_bounds).\n"
      "export default " + json.dumps(out, separators=(",", ":")) + ";\n")
(SITE / "js/representation-data.js").write_text(js)
print(f"wrote {len(fp)} fingerprints; missing: {missing or 'none'}")
