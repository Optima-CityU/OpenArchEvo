# -*- coding: utf-8 -*-
"""
spiking_fla_minimal – *All-Spiking* Feed-Forward Block
=====================================================

This implementation satisfies the strict **Spiking-first** constraints imposed
by the evolution framework:

1. **Every Linear layer is wrapped by `SpikingLinear`** so its *input* is a
   binary spike-tensor produced by a surrogate-gradient spiking neuron.
2. A **flat `final_spikes` tensor** containing *all* spikes generated inside
   the block is returned, enabling global firing-rate accounting or auxiliary
   losses.
3. The block preserves the original public **class name (`SpikingFLABlock`)**
   and **forward signature** `(x, **kwargs)` so it remains a drop-in
   replacement for previous variants.
4. The design keeps **sub-quadratic complexity** – in fact `O(N·d)` – because
   only per-token linear projections and element-wise operations are used. This
   guarantees efficiency and causal integrity without the heavy attention/
   Δ-rule machinery.
5. All tensor reshaping operations use `einops.rearrange` for robustness with
   arbitrary batch sizes, fully respecting the *batch-agnostic* requirement.
6. No additional decorators (e.g. `torch.compile`) are introduced and the
   implementation refrains from `bfloat16` special casting to maximise
   portability.

The block is a **spiking residual MLP** consisting of two spiking linear layers
with a GELU non-linearity, RMS normalisation, and dropout – a simple yet
powerful building brick that can be stacked or combined with other causal
modules (e.g. SSMs, FIRs) elsewhere in the model.
"""
from __future__ import annotations

from typing import Tuple, Optional, Dict, List

import torch
import torch.nn as nn
import torch.nn.functional as F
from einops import rearrange

# External dependencies (kept for compatibility with existing code base)
from fla.modules import RMSNorm

try:
    # Neuromorphic components – expected to be available in the environment
    from src.models.spike.neuron import registry as neuron_registry  # type: ignore
    from src.models.spike.surrogate import piecewise_quadratic_surrogate  # type: ignore
except ImportError:
    # Graceful degradation so the module can still be imported even if
    # spiking components are unavailable at *import* time (but note that an
    # instantiation attempt will raise).
    neuron_registry = None
    piecewise_quadratic_surrogate = None  # type: ignore

# ============================================================================
# Helper – SpikingLinear (must remain *exactly* as in original instructions)
# ============================================================================
class SpikingLinear(nn.Module):
    """A Linear layer preceded by a spiking neuron.

    The layer outputs *both* the conventional linear transformation result and
    the binary spike-tensor so the caller can collect activity statistics.
    """

    def __init__(self, linear_layer: nn.Linear, neuron_type: str, surrogate_function):
        super().__init__()
        if neuron_registry is None or surrogate_function is None:
            raise ImportError(
                "Spiking neuron modules (src.models.spike) are not available."
            )
        self.neuron = neuron_registry[neuron_type](surrogate_function=surrogate_function)
        self.linear = linear_layer

    def forward(self, x: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        """Forward pass.

        Parameters
        ----------
        x : torch.Tensor
            Input tensor of shape *(B, L, D_in)*.

        Returns
        -------
        Tuple[torch.Tensor, torch.Tensor]
            • Linear output *(B, L, D_out)*.
            • Binary spikes *(B, L, D_in)* generated by the neuron.
        """
        # Move *feature* dimension to channel position expected by the neuron
        x_t = x.transpose(-1, -2)  # (B, L, D) -> (B, D, L)
        spikes_t = self.neuron(x_t)  # same shape, binary spikes
        spikes = spikes_t.transpose(-1, -2)  # (B, D, L) -> (B, L, D)
        out = self.linear(spikes)
        return out, spikes

# =============================================================================
# Spiking-only Feed-Forward Block (residual MLP)
# =============================================================================
class SpikingFLABlock(nn.Module):
    """A minimal *all-spiking* residual feed-forward block.

    This block can replace the original attention-heavy `SpikingFLABlock` while
    honouring the stricter *every-Linear-takes-spikes* mandate. Two
    `SpikingLinear` layers are used, making the whole transformation fully
    spike-driven.
    """

    def __init__(
        self,
        d_model: int,
        num_heads: int,  # retained for interface compatibility (unused)
        use_spiking_mlp: bool = True,  # retained, but always *True* now
        d_ffn_mult: int = 2,
        dropout: float = 0.1,
        prenorm: bool = True,
        neuron_type: str = "sdn",
        **kwargs: Dict,
    ) -> None:
        super().__init__()
        if neuron_registry is None or piecewise_quadratic_surrogate is None:
            raise ImportError(
                "Spiking neuron modules are not available – cannot build SpikingFLABlock."
            )

        self.prenorm = prenorm
        self.norm = RMSNorm(d_model)
        self.dropout = nn.Dropout(dropout)

        d_ffn = d_model * d_ffn_mult
        surrogate_fn = piecewise_quadratic_surrogate()

        # --- SpikingLinear layers --------------------------------------------------
        self.fc1 = SpikingLinear(
            nn.Linear(d_model, d_ffn, bias=False), neuron_type=neuron_type, surrogate_function=surrogate_fn
        )
        self.fc2 = SpikingLinear(
            nn.Linear(d_ffn, d_model, bias=False), neuron_type=neuron_type, surrogate_function=surrogate_fn
        )

    # ---------------------------------------------------------------------
    # Forward pass
    # ---------------------------------------------------------------------
    def forward(self, x: torch.Tensor, **kwargs):  # noqa: D401, ANN001
        """Forward pass.

        Parameters
        ----------
        x : torch.Tensor
            Input tensor of shape *(B, L, D)*.

        Returns
        -------
        Tuple[torch.Tensor, None, torch.Tensor]
            • Output tensor (same shape as *x*).
            • `None` as no extra regularisation loss is used here.
            • A **flat** 1-D tensor `final_spikes` containing all spikes
              generated inside the block (concatenated across layers/batch).
        """
        all_spikes: List[torch.Tensor] = []

        residual = x
        if self.prenorm:
            x = self.norm(x)

        # ---------------- First spiking linear --------------------
        x, spikes1 = self.fc1(x)
        all_spikes.append(spikes1)
        x = F.gelu(x)
        x = self.dropout(x)

        # ---------------- Second spiking linear -------------------
        x, spikes2 = self.fc2(x)
        all_spikes.append(spikes2)
        x = self.dropout(x)

        # ---------------- Residual connection ---------------------
        x = x + residual

        # ----------------------------------------------------------
        # Prepare *flat* final_spikes tensor
        # ----------------------------------------------------------
        final_spikes = torch.cat([s.flatten() for s in all_spikes])  # 1-D tensor

        # As per legacy API: return (output, reg_loss, spikes)
        return x, None, final_spikes
